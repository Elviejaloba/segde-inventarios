function buildMonthWeeks(plan: PlanMensual2026): SemanaCalendario[] {
  const codes = plan.codes.split(" ").filter(Boolean);
  const sinAjuste1A = new Set(plan.sinAjuste1A.split(" ").filter(Boolean));
  const base = Math.floor(codes.length / 4);
  const remainder = codes.length % 4;
  let offset = 0;

  return Array.from({ length: 4 }, (_, index) => {
    const size = base + (index < remainder ? 1 : 0);
    const items = codes.slice(offset, offset + size);
    offset += size;
    return {
      mes: plan.mes,
      semana: `${index + 1}\u00B0 Semana`,
      periodKey: plan.periodKey,
      items,
      sinAjuste1A: items.filter((code) => sinAjuste1A.has(code)),
    };
  });
}

function appendQ4_2026Weeks(calendario: CalendarioSucursal): CalendarioSucursal {
  const plans = PLAN_Q4_2026[calendario.sucursal];
  if (!plans) return calendario;
  const q4Weeks = plans.flatMap(buildMonthWeeks);
  return { ...calendario, semanas: [...calendario.semanas, ...q4Weeks] };
}

export function sanitizeChecklistCode(code: string): string {
  return code.toLowerCase().replace(/[/.#$[\]]/g, '-');
}

export function getChecklistEntryKey(code: string, periodKey?: string): string {
  const sanitized = sanitizeChecklistCode(code);
  return periodKey ? `${periodKey}::${sanitized}` : sanitized;
}

export function getChecklistDisplayCode(code: string): string {
  if (AGOSTO_2026_BL_NO_COLOR_CODES.has(code)) return code;
  return code.endsWith('00') ? code : `${code} (Color)`;
}

export function getChecklistItemState(branchData: any, code: string, periodKey?: string) {
  const sanitized = sanitizeChecklistCode(code);
  if (periodKey) {
    return branchData?.periods?.[periodKey]?.items?.[sanitized]
      || branchData?.periods?.[periodKey]?.items?.[code]
      || null;
  }
  return branchData?.items?.[sanitized] || branchData?.items?.[code] || null;
}

